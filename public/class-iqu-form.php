    // ════════════════════════════════════════════════════
    // AJAX handler
    // ════════════════════════════════════════════════════
    public function handle_ajax_submit(): void
    {
        // CSRF
        if (!check_ajax_referer('iqu_registration_nonce', '_iqu_nonce', false)) {
            wp_send_json_error(['message' => 'Security check failed. Please refresh the page and try again.', 'code' => 'invalid_nonce']);
        } 

        // Honeypot
        if (!empty($_POST['iqu_website'])) {
            wp_send_json_success(['message' => 'Thank you! Your registration has been received.']);
        }

        // reCAPTCHA v3
        $token = sanitize_text_field($_POST['iqu_recaptcha_token'] ?? '');
        $verify = IQU_Recaptcha::verify($token, 'iqu_free_form');
        if (!$verify['success']) {
            wp_send_json_error(['message' => 'Verification failed. Please try again.', 'code' => 'recaptcha_failed']);
        }

        // Validate
        $validator = new IQU_Validator();
        if (!$validator->validate_free($_POST)) {
            wp_send_json_error([
                'message' => 'Please fix the errors below.',
                'errors' => $validator->get_errors(),
                'code' => 'validation_failed',
            ]);
        }

        $clean = $validator->get_clean();

        // Duplicate email check within this form type
        // if (IQU_Database::email_exists($clean['email'], IQU_Database::FORM_FREE)) {
        //   wp_send_json_error([
        //     'message' => 'This email is already registered for free enrollment. Please use a different email or contact us.',
        //     'errors' => ['email' => 'This email is already registered.'],
        //     'code' => 'duplicate_email',
        //   ]);
        // }

        // ── Free form: fee_pref থেকে payment_amount বের করো ──
        $fee_amount_map = [
            'arabic_50'  => 50.00,
            'hifz_100'   => 100.00,
            'hifz_90'    => 90.00,
            'hifz_80'    => 80.00,
            'hifz_70'    => 70.00,
            'hifz_60'    => 60.00,
            'qaidah_80'  => 80.00,
            'qaidah_70'  => 70.00,
            'qaidah_60'  => 60.00,
            'qaidah_50'  => 50.00,
            'free'       => 0.00,
        ];

        $fee_pref = $clean['fee_pref'] ?? '';

        if (isset($fee_amount_map[$fee_pref])) {
            $clean['payment_amount'] = $fee_amount_map[$fee_pref];
        } elseif ($fee_pref === 'other') {
            // flexible_fee_note থেকে numeric amount বের করো
            $note = trim($clean['flexible_fee_note'] ?? '');
            $note_clean = ltrim($note, '$');
            $clean['payment_amount'] = is_numeric($note_clean) ? (float) $note_clean : 0.00;
        } else {
            $clean['payment_amount'] = 0.00;
        }

        // Free form-এ payment_status সবসময় pending (cash/zelle পরে confirm হবে)
        $clean['payment_status'] = $fee_pref === 'free' ? 'pending' : 'pending';

        // Insert
        $reg_id = IQU_Database::insert_registration($clean);
        if (!$reg_id) {
            error_log('[IQU] Free registration DB insert failed.');
            wp_send_json_error(['message' => 'Registration failed due to a server error. Please try again or contact us.', 'code' => 'db_error']);
        }

        // Emails
        IQU_Mailer::send_admin_notification($clean, $reg_id);
        IQU_Mailer::send_student_confirmation($clean);

        // ── Meta Lead event (browser + server, event_id দিয়ে dedup) ──
        $event_id     = IQU_Pixel::new_event_id();
        $content_name = 'Free Enrollment';
        $lead_value   = (float) ($clean['payment_amount'] ?? 0);

        IQU_Pixel::send_lead($clean, $event_id, [
            'content_name' => $content_name,
            'value'        => $lead_value,
        ]);

        wp_send_json_success([
            'message' => "JazakAllahu Khairan! Your registration has been received. We will contact you via WhatsApp within 24–48 hours, in-sha'-Allah.",
            'reg_id' => $reg_id,
            'form' => 'free',
            'event_id'     => $event_id,
            'content_name' => $content_name,
            'value'        => $lead_value,
        ]);
    }
