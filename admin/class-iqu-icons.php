    public static function has(string $name): bool
    {
        return isset(self::PATHS[$name]);
    }

    public static function names(): array
    {
        return array_keys(self::PATHS);
    }

    /** The bare SVG (decorative). */
    public static function svg(string $name, int $size = 20): string
    {
        $inner = self::PATHS[$name] ?? self::PATHS['info'];
        return '<svg class="iqu-icon iqu-icon--' . esc_attr($name) . '" xmlns="http://www.w3.org/2000/svg" width="' . $size . '" height="' . $size . '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' . $inner . '</svg>';
    }

    /** The icon on its soft tinted square, in one of TONES. */
    public static function badge(string $name, string $tone = 'navy'): string
    {
        $tone = in_array($tone, self::TONES, true) ? $tone : 'navy';
        return '<span class="iqu-stat-icon iqu-tone--' . $tone . '" aria-hidden="true">' . self::svg($name) . '</span>';
    }

    /**
     * Head row of a stat card: icon on the left, the number right next to it. $value_html is trusted
     * HTML from the caller (already escaped); $num_class adds classes to the number element.
     */
    public static function stat_head(string $icon, string $tone, string $value_html, string $num_class = ''): string
    {
        return '<div class="iqu-stat-head">' . self::badge($icon, $tone)
            . '<div class="iqu-metric-num' . ($num_class !== '' ? ' ' . esc_attr($num_class) : '') . '">' . $value_html . '</div></div>';
    }
